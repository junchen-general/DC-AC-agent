function basis = dcac_loss_basis(e)
%DCAC_LOSS_BASIS Machine-readable provenance for the preliminary device model.
datasheetSource = struct( ...
    'kind','manufacturer_datasheet', ...
    'manufacturer','Infineon Technologies AG', ...
    'document','IPW65R041CFD7 650 V CoolMOS CFD7 SJ Power Device', ...
    'revision','2.1', ...
    'date','2020-08-12', ...
    'url','https://www.infineon.com/assets/row/public/documents/24/49/infineon-ipw65r041cfd7-datasheet-en.pdf', ...
    'tables','Table 4 static, Table 5 dynamic, Table 7 reverse diode', ...
    'status','manufacturer_datasheet_defaults');
if strcmp(e.device_parameter_source_status,'manufacturer_datasheet_defaults')
    source=datasheetSource;
elseif strcmp(e.device_parameter_source_status,'user_supplied_with_source')
    source=e.device_source;
    source.status='user_supplied_with_source';
else
    source=struct('kind','user_supplied','status','user_supplied_unverified');
end
diodeRonSource=struct('kind','modeling_assumption','status','assumed_unverified');
basis = struct;
basis.schema_version = 'dcac.loss-basis/1.0';
basis.device = e.device_part;
basis.parameter_source_status=e.device_parameter_source_status;
basis.assumed_junction_temperature_c = e.device_junction_temperature_c;
basis.parameters = [ ...
    parameter('device_rds_on_ohm',e.device_rds_on_ohm,'ohm', ...
        'typical at Tj=150 C, Vgs=10 V and Id=24.8 A',source), ...
    parameter('device_diode_vf_v',e.device_diode_vf_v,'V', ...
        'typical at Tj=25 C and If=24.8 A',source), ...
    parameter('device_diode_ron_ohm',e.device_diode_ron_ohm,'ohm', ...
        'numerical on-resistance used by the SPS diode branch; not a datasheet value',diodeRonSource), ...
    parameter('device_rise_time_s',e.device_rise_time_s,'s', ...
        'typical at Vdd=400 V, Vgs=13 V, Id=24.8 A and Rg=3.3 ohm',source), ...
    parameter('device_fall_time_s',e.device_fall_time_s,'s', ...
        'typical at Vdd=400 V, Vgs=13 V, Id=24.8 A and Rg=3.3 ohm',source), ...
    parameter('device_reverse_recovery_charge_c',e.device_reverse_recovery_charge_c,'C', ...
        'typical at Vr=400 V, If=24.8 A and di/dt=100 A/us',source)];
basis.method = ['Device conduction is evaluated from simulated current and Rds(on). ' ...
    'Switching overlap uses 0.5*V*I*(tr+tf) per transition. Reverse recovery is ' ...
    'reported separately and is not included in a claimed whole-inverter efficiency.'];
basis.limitations = { ...
    'Datasheet switching conditions are far above the approximately 2.3 Arms course-design operating point.', ...
    'No nonlinear capacitance, gate-drive impedance, thermal iteration, capacitor ESR, magnetic core loss, or auxiliary loss is closed.', ...
    'The default winding resistance has no material/geometry/temperature provenance; I^2R is DC-ohmic-only.', ...
    'No total or whole-inverter efficiency may be claimed from these parameters alone.'};
end

function out = parameter(name,value,unit,condition,source)
out = struct('name',name,'value',value,'unit',unit,'test_condition',condition,'source',source);
end
