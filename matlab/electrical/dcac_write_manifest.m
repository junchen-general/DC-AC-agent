function manifest = dcac_write_manifest(outdir,request,result,modelFile)
%DCAC_WRITE_MANIFEST Self-describing provenance and B-to-C handoff contract.
[s,e,context]=dcac_normalize_request(request);
manifest=struct;
manifest.schema_version='dcac.electrical.handoff/1.0';
manifest.status=ternary(result.ok,'success','failed');
manifest.data_origin=ternary(result.ok && strcmp(request.action,'simulate'),'real_simulation','not_run');
manifest.created_utc=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
manifest.identity=struct('session_id',context.session_id,'design_revision',context.design_revision, ...
    'run_id',context.run_id,'case_id',e.scenario_id, ...
    'comparison_group_id',context.comparison_group_id, ...
    'component_revision_id',context.component_revision_id, ...
    'parent_component_revision_id',context.parent_component_revision_id, ...
    'design_fingerprint_sha256',hashText(jsonencode(s)));
manifest.model=struct('stage',e.model_fidelity,'fidelity',fidelityDescription(e.model_fidelity), ...
    'open_or_closed_loop',ternary(contains(e.model_fidelity,'closed_loop'),'closed_loop','open_loop'), ...
    'dead_time_s',e.dead_time_s,'dead_time_requested_s',e.dead_time_requested_s, ...
    'dead_time_effective_s',e.dead_time_effective_s,'dead_time_quantization_error_s',e.dead_time_quantization_error_s, ...
    'closed_loop_dead_time_compensation',e.closed_loop_dead_time_compensation, ...
    'base_modulation_index',e.base_modulation_index, ...
    'dead_time_compensation_index',e.dead_time_compensation_index, ...
    'feedforward_modulation_index',e.feedforward_modulation_index, ...
    'controller',struct('kp_per_V',e.controller_kp_per_v, ...
        'kr_per_V',e.controller_kr_per_v,'bandwidth_Hz',e.controller_bandwidth_hz), ...
    'loss_model_enabled',contains(e.model_fidelity,'lossy') || contains(e.model_fidelity,'closed_loop'), ...
    'slx_path',modelFile,'script_path','dcac_execute.m');
manifest.environment=struct('matlab_version',version,'simulink_version',productVersion('Simulink'), ...
    'simscape_electrical_version',productVersion('Simscape Electrical'), ...
    'required_products',{requiredElectricalProducts(e.model_fidelity)});
manifest.spec=s;
ratedResistance=s.output_voltage^2/s.output_power;
[physicalInitialG,physicalFinalG]=expectedPhysicalConductance(ratedResistance,e);
manifest.operating_condition=struct('scenario',e.scenario_id,'vin_V',s.input_voltage, ...
    'fundamental_frequency_Hz',s.output_frequency,'switching_frequency_Hz',s.switching_frequency, ...
    'rated_load_resistance_ohm',ratedResistance, ...
    'load_ratio_initial',e.load_ratio_initial,'load_ratio_final',e.load_ratio_final, ...
    'initial_load_resistance_ohm',ratedResistance/e.load_ratio_initial, ...
    'final_load_resistance_ohm',ratedResistance/e.load_ratio_final, ...
    'initial_load_conductance_S',e.load_ratio_initial/ratedResistance, ...
    'final_load_conductance_S',e.load_ratio_final/ratedResistance, ...
    'expected_physical_initial_load_conductance_S',physicalInitialG, ...
    'expected_physical_final_load_conductance_S',physicalFinalG, ...
    'breaker_on_resistance_ohm',e.load_breaker_on_resistance_ohm, ...
    'initial_target_power_W',s.output_power*e.load_ratio_initial, ...
    'final_target_power_W',s.output_power*e.load_ratio_final, ...
    'load_step_enabled',e.load_step_enabled, ...
    'load_step_time_s',s.load_step_time,'soft_start_s',e.soft_start_s, ...
    'legacy_load_step_requested',e.legacy_load_step_requested, ...
    'legacy_condition_overridden',e.legacy_condition_overridden, ...
    'device_junction_temperature_assumption_C',e.device_junction_temperature_c, ...
    'winding_temperature_assumption_C',[]);
if isfield(result,'electrical_v1') && isfield(result.electrical_v1,'sampling') && ...
        isfield(result.electrical_v1,'metrics')
    manifest.sampling=result.electrical_v1.sampling;
    manifest.windows=result.electrical_v1.windows;
    manifest.metrics_by_window=struct( ...
        'thd_steady',struct('window_id','thd_steady','legacy',result.metrics, ...
        'electrical_detail',result.electrical_v1.metrics,'losses',result.electrical_v1.losses), ...
        'transient',struct('window_id','transient','metrics',result.electrical_v1.dynamic));
    manifest.loss_models=result.electrical_v1.losses;
else
    manifest.sampling=struct('solver',e.solver_name,'solver_type',e.solver_type, ...
        'fixed_step_s',e.fixed_step_s,'status','not_simulated');
    manifest.windows=[]; manifest.metrics_by_window=struct; manifest.loss_models=struct;
end
manifest.signals=signalDictionary();
manifest.thd_definition=struct('fundamental_Hz',s.output_frequency,'harmonic_min',2, ...
    'harmonic_max',40,'window_cycles',4,'window_function','rectangular', ...
    'right_endpoint_excluded',true,'carrier_band_included',false, ...
    'switching_bands_reported_separately_Hz',[0.5*s.switching_frequency 1.5*s.switching_frequency; ...
    1.5*s.switching_frequency 2.5*s.switching_frequency]);
manifest.artifacts=artifactList(outdir);
manifest.artifact_inventory_note='run_manifest.json is omitted from its own pre-write hash inventory.';
lossBasisPath=fullfile(outdir,'loss_basis_v1.json');
if isfile(lossBasisPath)
    manifest.loss_basis_file='loss_basis_v1.json'; manifest.loss_basis_status='present';
else
    manifest.loss_basis_file=[]; manifest.loss_basis_status='not_generated_without_simulation';
end
manifest.step_size_comparison=comparisonInfo(context);
manifest.limitations={ ...
    'Web JSON waveforms are decimated for display and are not valid C inputs.', ...
    'Use electrical_raw_v1.mat or electrical_full_v1.csv for full-resolution coupling.', ...
    'The winding-resistance loss is DC-ohmic-only and the default resistance has no temperature/material provenance.', ...
    'The semiconductor loss model is preliminary and does not close whole-inverter efficiency.', ...
    'Magnetic core, capacitor ESR, gate drive, control supply, auxiliary and thermal feedback losses are excluded.'};
if e.closed_loop_dead_time_compensation
    manifest.limitations{end+1}=[ ...
        'Dead-time feedforward is a first-harmonic approximation (Delta m=8*f_sw*t_dead/pi); ' ...
        'it is not a device-level nonlinear dead-time observer.'];
end
if strcmp(request.action,'simulate') && ...
        ~isfile(fullfile(outdir,'electrical_raw_v1.mat')) && ...
        ~isfile(fullfile(outdir,'electrical_full_v1.csv'))
    manifest.limitations{end+1}=[ ...
        'Full-resolution waveform data were not retained for this storage-bounded case; ' ...
        'rerun request.json to regenerate them. Metrics, plots and the editable model remain.'];
end
if isempty(context.design_revision)
    manifest.limitations{end+1}=['design_revision was not supplied by the A-side caller. ' ...
        'The complete spec fingerprint and run directory remain available; A must inject the revision for final handoff.'];
end
if isempty(context.component_revision_id)
    manifest.limitations{end+1}='component_revision_id was not supplied; do not treat this run as a C-return revalidation.';
end
if strcmp(e.device_parameter_source_status,'user_supplied_unverified')
    manifest.limitations{end+1}='Device parameters were overridden without a source and are marked user_supplied_unverified.';
end
dcac_write_json(fullfile(outdir,'run_manifest.json'),manifest);
end

function definitions=signalDictionary()
names={'sample_index_0based','time_s','i_inductor_A','v_bridge_V','v_out_V','i_load_A','load_conductance_S', ...
    'v_inductor_terminal_V','v_winding_resistive_V','v_inductive_V','i_capacitor_A', ...
    'p_winding_resistive_W','gate_a_upper','gate_a_lower','gate_b_upper','gate_b_lower','i_dc_A','v_dc_V'};
units={'1','s','A','V','V','A','S','V','V','V','A','W','1','1','1','1','A','V'};
descriptions={ ...
    'zero-based row index in the full-resolution export','simulation time', ...
    'positive from bridge leg A through the filter to the load', ...
    'bridge terminal A minus terminal B','load/output node minus bridge return', ...
    'positive from output node into the resistive load','instantaneous commanded load conductance', ...
    'v_bridge-v_out across DCR plus ideal inductance','rL*i_inductor', ...
    'v_bridge-v_out-rL*i_inductor; voltage used for magnetic flux linkage', ...
    'positive into the shunt capacitor','i_inductor^2*rL with constant rL', ...
    'leg A upper gate','leg A lower gate','leg B upper gate','leg B lower gate', ...
    'positive from DC source into the bridge','DC source voltage'};
definitions=repmat(struct('name','','unit','','description','','mat_path','','csv_column',''),1,numel(names));
for k=1:numel(names)
    definitions(k)=struct('name',names{k},'unit',units{k},'description',descriptions{k}, ...
        'mat_path',['signals.' names{k}],'csv_column',names{k});
end
end

function items=artifactList(outdir)
listing=dir(outdir); listing=listing(~[listing.isdir]);
listing=listing(~strcmp({listing.name},'run_manifest.json'));
items=repmat(struct('path','','type','','sha256','','bytes',0),1,numel(listing));
for k=1:numel(listing)
    path=fullfile(outdir,listing(k).name);
    items(k)=struct('path',listing(k).name,'type',artifactType(listing(k).name), ...
        'sha256',hashFile(path),'bytes',listing(k).bytes);
end
end

function value=hashFile(path)
try
    fid=fopen(path,'rb'); cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
    value=hashBytes(fread(fid,inf,'*uint8'));
catch
    value='';
end
end

function value=hashText(text)
value=hashBytes(unicode2native(text,'UTF-8'));
end

function value=hashBytes(bytes)
try
    md=java.security.MessageDigest.getInstance('SHA-256');
    md.update(typecast(uint8(bytes),'int8'));
    digest=typecast(md.digest(),'uint8');
    value=lower(reshape(dec2hex(digest,2).',1,[]));
catch
    value='';
end
end

function value=artifactType(name)
[~,~,ext]=fileparts(name);
switch lower(ext)
    case '.slx', value='simulink_model';
    case '.mat', value='matlab_data';
    case '.csv', value='tabular_data';
    case '.png', value='plot';
    case '.m', value='matlab_source';
    case '.json', value='metadata';
    otherwise, value='other';
end
end

function value=productVersion(name)
p=ver(name);
if isempty(p)
    installed=ver;
    match=find(strcmpi({installed.Name},name),1);
    if ~isempty(match), p=installed(match); end
end
if isempty(p), value='not_available'; else, value=p(1).Version; end
end

function value=requiredElectricalProducts(fidelity)
value={'MATLAB','Simulink'};
if startsWith(fidelity,'sps_'), value{end+1}='Simscape Electrical Specialized Power Systems'; end
end

function value=comparisonInfo(context)
if isempty(context.comparison_group_id)
    value=struct('status','not_in_single_run','comparison_group_id','', ...
        'peer_run_ids',{{}},'study_path',[], ...
        'instructions','Use dcac_validate.m to create paired fixed-step runs.');
else
    value=struct('status','pending_until_matrix_complete', ...
        'comparison_group_id',context.comparison_group_id, ...
        'peer_run_ids',{context.comparison_peer_run_ids}, ...
        'study_path','../time_step_study_v1.json');
end
end

function [initialValue,finalValue]=expectedPhysicalConductance(r,e)
finalValue=e.load_ratio_final/r;
if e.load_step_enabled
    initialValue=finalValue+1/(r/(1-e.load_ratio_final)+e.load_breaker_on_resistance_ohm);
else
    initialValue=e.load_ratio_initial/r;
end
end

function value=fidelityDescription(fidelity)
switch fidelity
    case 'baseline_ideal_switching_open_loop'
        value='ideal switching function plus continuous LC equations; no semiconductor commutation';
    case 'sps_device_open_loop'
        value='four explicit idealized SPS MOSFET devices with body diodes and dead time';
    case 'sps_device_lossy_open_loop'
        value='four SPS MOSFET devices with datasheet-derived static parameters and preliminary loss ledger';
    otherwise
        value='four SPS MOSFET devices, dead time, preliminary losses and PR voltage loop';
end
end

function value=ternary(condition,left,right)
if condition, value=left; else, value=right; end
end
